export type QuebecRegulation = "full" | "partial" | "none";

export function quebecRegulation(noc: string | null | undefined): QuebecRegulation {
  if (!noc) return "none";
  if (fullyRegulatedNoc.has(noc)) return "full";
  if (partiallyRegulatedNoc.has(noc)) return "partial";
  return "none";
}
