function snap10(value: number) {
  return Math.round(value / 10) * 10;
}

function livingCity(
  id: string,
  name: string,
  province: string,
  housing2: number,
  patch: Partial<Omit<LivingCity, "id" | "name" | "province" | "housing2">> = {},
): LivingCity {
  const region = REGION[province];
  return {
    id,
    name,
    province,
    housing2,
    housing1: patch.housing1 ?? snap10(housing2 * 0.78),
    grocery: patch.grocery ?? region.grocery,
    transport: patch.transport ?? region.transport,
    utilities: patch.utilities ?? region.utilities,
    childcare: patch.childcare ?? region.childcare,
  };
}

