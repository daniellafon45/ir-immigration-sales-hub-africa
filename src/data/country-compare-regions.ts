export function compareRegionFor(country: string): CompareRegionId {
  const name = country.trim() as Country;
  if (name && name in countryCompareRegionByCountry) {
    return countryCompareRegionByCountry[name];
  }
  return "west_africa_other";
}

/** Runtime check helper used by tests. */
export function missingCompareRegions(): string[] {
  return countries.filter((c) => !(c in countryCompareRegionByCountry));
}
